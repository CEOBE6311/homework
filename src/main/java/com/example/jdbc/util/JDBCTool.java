package com.example.jdbc.util;

import com.example.jdbc.annotation.Column;
import com.example.jdbc.annotation.Id;
import com.example.jdbc.annotation.Table;

import java.io.IOException;
import java.io.InputStream;
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Properties;
import java.util.stream.Collectors;

/**
 * JDBCTool —— 一个基于「Java 反射 + JDBC」实现的轻量 ORM 工具类。
 *
 * <p>ORM（Object Relational Mapping，对象关系映射）的基本原理：</p>
 * <ol>
 *   <li>类与表对应：@Table 注解描述 类 -> 表 的映射；</li>
 *   <li>属性与字段对应：@Column 注解描述 属性 -> 字段 的映射；</li>
 *   <li>对象与记录对应：resultSetToList 用反射创建对象（无参构造）
 *       并把 ResultSet 一行记录的值 set 到对象属性上；</li>
 *   <li>对象操作与 SQL 对应：save/update/delete 用反射读出对象属性值，
 *       自动拼接 INSERT / UPDATE / DELETE 语句，通过 PreparedStatement 执行。</li>
 * </ol>
 *
 * <p>统一访问的五个方法（作业要求）：</p>
 * <ol>
 *   <li>resultSetToList(ResultSet, Class) —— 查：结果集 -> 对象列表</li>
 *   <li>save(T obj, Connection)            —— 增：插入一条记录</li>
 *   <li>update(T obj, Connection)          —— 改：按主键更新</li>
 *   <li>delete(T obj, Connection)          —— 删：按主键删除</li>
 *   <li>getOneById(String, Class, Connection) —— 查：按主键获取一个对象</li>
 * </ol>
 */
public final class JDBCTool {

    private JDBCTool() {
    }

    // ==================== 辅助方法：数据库统一访问 ====================

    /**
     * 从 classpath 下的 db.properties 读取配置，创建数据库连接。
     */
    public static Connection getConnection() throws SQLException {
        Properties props = new Properties();
        try (InputStream in = JDBCTool.class.getClassLoader().getResourceAsStream("db.properties")) {
            if (in == null) {
                throw new SQLException("未找到配置文件 db.properties");
            }
            props.load(in);
        } catch (IOException e) {
            throw new SQLException("读取数据库配置文件失败", e);
        }
        try {
            Class.forName(props.getProperty("jdbc.driver"));
        } catch (ClassNotFoundException e) {
            throw new SQLException("加载数据库驱动失败: " + props.getProperty("jdbc.driver"), e);
        }
        return DriverManager.getConnection(
                props.getProperty("jdbc.url"),
                props.getProperty("jdbc.username"),
                props.getProperty("jdbc.password"));
    }

    /**
     * 统一关闭 JDBC 资源（Connection / Statement / ResultSet 都实现了 AutoCloseable）。
     */
    public static void close(AutoCloseable... resources) {
        for (AutoCloseable resource : resources) {
            if (resource != null) {
                try {
                    resource.close();
                } catch (Exception ignored) {
                    // 关闭失败不影响主流程
                }
            }
        }
    }

    // ==================== 方法1：查询 —— ResultSet -> 对象列表 ====================

    /**
     * 把 ResultSet 中所有记录转换成 clazz 类型的对象列表。
     * <p>反射的运用：clazz.getDeclaredConstructor().newInstance() 创建对象，
     * field.setAccessible(true) + field.set() 完成属性赋值，
     * 每条记录的字段值自动转换为属性对应类型。</p>
     */
    public static <T> List<T> resultSetToList(ResultSet rs, Class<T> clazz) throws Exception {
        List<T> list = new ArrayList<>();
        List<Field> fields = columnFields(clazz);
        while (rs.next()) {
            // 反射：调用无参构造创建对象
            T instance = clazz.getDeclaredConstructor().newInstance();
            for (Field field : fields) {
                Object value = readColumnValue(rs, columnName(field), field.getType());
                // 反射：绕过 private 限制给属性赋值
                field.setAccessible(true);
                field.set(instance, value);
            }
            list.add(instance);
        }
        return list;
    }

    // ==================== 方法2：增 —— 保存对象（INSERT） ====================

    /**
     * 保存对象到数据库：根据对象属性自动生成
     * INSERT INTO 表名 (字段1, 字段2, ...) VALUES (?, ?, ...)
     * 自增主键为空或为 0 时自动跳过（交给数据库生成），
     * 保存成功后通过 getGeneratedKeys 把数据库生成的主键回填到对象上。
     *
     * @return 受影响的行数
     */
    public static <T> int save(T obj, Connection connection) throws Exception {
        Class<?> clazz = obj.getClass();
        String table = tableName(clazz);
        List<Field> insertFields = new ArrayList<>();
        boolean autoGeneratedId = false;
        for (Field field : columnFields(clazz)) {
            if (isIdField(field)) {
                field.setAccessible(true);
                Object idValue = field.get(obj);
                // 主键为空或为 0：交给数据库自增生成
                if (idValue == null || (idValue instanceof Number n && n.longValue() == 0)) {
                    autoGeneratedId = true;
                    continue;
                }
            }
            insertFields.add(field);
        }
        if (insertFields.isEmpty()) {
            throw new IllegalArgumentException("对象没有可保存的字段: " + clazz.getName());
        }

        String columns = insertFields.stream().map(JDBCTool::columnName).collect(Collectors.joining(", "));
        String placeholders = String.join(", ", Collections.nCopies(insertFields.size(), "?"));
        String sql = "INSERT INTO " + table + " (" + columns + ") VALUES (" + placeholders + ")";

        try (PreparedStatement ps = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            bind(ps, insertFields, obj, 1);
            int rows = ps.executeUpdate();
            // 反射：把数据库生成的自增主键回填到对象的主键属性上
            if (autoGeneratedId) {
                Field idField = idField(clazz);
                idField.setAccessible(true);
                try (ResultSet keys = ps.getGeneratedKeys()) {
                    if (keys.next()) {
                        idField.set(obj, convertToId(keys.getObject(1), idField.getType()));
                    }
                }
            }
            return rows;
        }
    }

    // ==================== 方法3：改 —— 更新对象（UPDATE） ====================

    /**
     * 按主键更新对象：自动生成
     * UPDATE 表名 SET 字段1 = ?, 字段2 = ?, ... WHERE id = ?
     *
     * @return 受影响的行数
     */
    public static <T> int update(T obj, Connection connection) throws Exception {
        Class<?> clazz = obj.getClass();
        String table = tableName(clazz);
        Field idField = idField(clazz);
        idField.setAccessible(true);
        Object idValue = idField.get(obj);
        if (idValue == null) {
            throw new IllegalArgumentException("更新对象缺少主键值: " + clazz.getName());
        }

        List<Field> setFields = new ArrayList<>();
        for (Field field : columnFields(clazz)) {
            if (!isIdField(field)) {
                setFields.add(field);
            }
        }
        String setClause = setFields.stream()
                .map(f -> columnName(f) + " = ?")
                .collect(Collectors.joining(", "));
        String sql = "UPDATE " + table + " SET " + setClause + " WHERE " + columnName(idField) + " = ?";

        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            bind(ps, setFields, obj, 1);
            bindValue(ps, setFields.size() + 1, idField.getType(), idValue);
            return ps.executeUpdate();
        }
    }

    // ==================== 方法4：删 —— 删除对象（DELETE） ====================

    /**
     * 按主键删除对象：自动生成 DELETE FROM 表名 WHERE id = ?
     *
     * @return 受影响的行数
     */
    public static <T> int delete(T obj, Connection connection) throws Exception {
        Class<?> clazz = obj.getClass();
        Field idField = idField(clazz);
        idField.setAccessible(true);
        Object idValue = idField.get(obj);
        if (idValue == null) {
            throw new IllegalArgumentException("删除对象缺少主键值: " + clazz.getName());
        }
        String sql = "DELETE FROM " + tableName(clazz) + " WHERE " + columnName(idField) + " = ?";
        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            bindValue(ps, 1, idField.getType(), idValue);
            return ps.executeUpdate();
        }
    }

    // ==================== 方法5：查 —— 按主键获取一个对象 ====================

    /**
     * 按主键查询并返回一个对象：
     * SELECT * FROM 表名 WHERE id = ?
     * 底层复用了 resultSetToList 完成"结果集 -> 对象"的映射。
     */
    public static <T> T getOneById(String id, Class<T> clazz, Connection connection) throws Exception {
        Field idField = idField(clazz);
        String sql = "SELECT * FROM " + tableName(clazz) + " WHERE " + columnName(idField) + " = ?";
        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setObject(1, convert(id, idField.getType()));
            try (ResultSet rs = ps.executeQuery()) {
                List<T> list = resultSetToList(rs, clazz);
                return list.isEmpty() ? null : list.get(0);
            }
        }
    }

    // ==================== 辅助方法：映射规则（反射元数据） ====================

    /** 反射读取 @Table 注解得到表名；没有注解时按类名驼峰转下划线 */
    private static String tableName(Class<?> clazz) {
        Table table = clazz.getAnnotation(Table.class);
        return table != null ? table.value() : toSnakeCase(clazz.getSimpleName());
    }

    /** 反射读取 @Column 注解得到字段名；没有注解时按属性名驼峰转下划线 */
    private static String columnName(Field field) {
        Column column = field.getAnnotation(Column.class);
        if (column != null && !column.value().isEmpty()) {
            return column.value();
        }
        return toSnakeCase(field.getName());
    }

    /** 反射获取实体类中需要映射的字段（非 static、非 transient） */
    private static List<Field> columnFields(Class<?> clazz) {
        List<Field> fields = new ArrayList<>();
        for (Field field : clazz.getDeclaredFields()) {
            int mod = field.getModifiers();
            if (Modifier.isStatic(mod) || Modifier.isTransient(mod)) {
                continue;
            }
            fields.add(field);
        }
        return fields;
    }

    /** 反射定位主键字段：优先 @Id 注解，其次名为 id 的属性 */
    private static Field idField(Class<?> clazz) {
        for (Field field : clazz.getDeclaredFields()) {
            if (field.isAnnotationPresent(Id.class) || field.getName().equalsIgnoreCase("id")) {
                return field;
            }
        }
        throw new IllegalArgumentException("实体类没有主键字段(@Id 或 id): " + clazz.getName());
    }

    private static boolean isIdField(Field field) {
        return field.isAnnotationPresent(Id.class) || field.getName().equalsIgnoreCase("id");
    }

    /** 驼峰转下划线：enrollDate -> enroll_date */
    private static String toSnakeCase(String camel) {
        StringBuilder sb = new StringBuilder();
        for (char c : camel.toCharArray()) {
            if (Character.isUpperCase(c)) {
                sb.append('_').append(Character.toLowerCase(c));
            } else {
                sb.append(c);
            }
        }
        return sb.toString();
    }

    /** 反射读出对象各属性值，依次绑定到 PreparedStatement 的占位符上 */
    private static void bind(PreparedStatement ps, List<Field> fields, Object obj, int startIndex) throws Exception {
        int index = startIndex;
        for (Field field : fields) {
            field.setAccessible(true);
            bindValue(ps, index++, field.getType(), field.get(obj));
        }
    }

    /** 按属性类型把值绑定到 PreparedStatement */
    private static void bindValue(PreparedStatement ps, int index, Class<?> type, Object value) throws SQLException {
        if (value == null) {
            ps.setObject(index, null);
        } else if (type == boolean.class || type == Boolean.class) {
            ps.setBoolean(index, (Boolean) value);
        } else if (type == int.class || type == Integer.class) {
            ps.setInt(index, (Integer) value);
        } else if (type == long.class || type == Long.class) {
            ps.setLong(index, (Long) value);
        } else if (type == double.class || type == Double.class) {
            ps.setDouble(index, (Double) value);
        } else if (type == float.class || type == Float.class) {
            ps.setFloat(index, (Float) value);
        } else if (type == BigDecimal.class) {
            ps.setBigDecimal(index, (BigDecimal) value);
        } else if (type == String.class) {
            ps.setString(index, (String) value);
        } else if (type == LocalDate.class) {
            ps.setDate(index, java.sql.Date.valueOf((LocalDate) value));
        } else if (type == LocalDateTime.class) {
            ps.setTimestamp(index, Timestamp.valueOf((LocalDateTime) value));
        } else if (type == java.util.Date.class) {
            ps.setTimestamp(index, new Timestamp(((java.util.Date) value).getTime()));
        } else {
            ps.setObject(index, value);
        }
    }

    /** 从 ResultSet 中按字段名取值，并转换成属性对应的 Java 类型 */
    private static Object readColumnValue(ResultSet rs, String column, Class<?> type) throws SQLException {
        Object raw = rs.getObject(column);
        if (raw == null) {
            return null;
        }
        if (type == boolean.class || type == Boolean.class) {
            if (raw instanceof Boolean b) {
                return b;
            }
            if (raw instanceof Number n) {
                return n.intValue() != 0;
            }
            return Boolean.parseBoolean(raw.toString());
        }
        if (type == int.class || type == Integer.class) {
            return ((Number) raw).intValue();
        }
        if (type == long.class || type == Long.class) {
            return ((Number) raw).longValue();
        }
        if (type == double.class || type == Double.class) {
            return ((Number) raw).doubleValue();
        }
        if (type == float.class || type == Float.class) {
            return ((Number) raw).floatValue();
        }
        if (type == BigDecimal.class) {
            return raw instanceof BigDecimal bigDecimal ? bigDecimal : new BigDecimal(raw.toString());
        }
        if (type == String.class) {
            return raw.toString();
        }
        if (type == LocalDate.class) {
            if (raw instanceof LocalDate ld) {
                return ld;
            }
            if (raw instanceof java.sql.Date d) {
                return d.toLocalDate();
            }
            if (raw instanceof Timestamp ts) {
                return ts.toLocalDateTime().toLocalDate();
            }
        }
        if (type == LocalDateTime.class) {
            if (raw instanceof LocalDateTime ldt) {
                return ldt;
            }
            if (raw instanceof Timestamp ts) {
                return ts.toLocalDateTime();
            }
        }
        if (type == java.util.Date.class) {
            if (raw instanceof java.util.Date d) {
                return d;
            }
            if (raw instanceof LocalDateTime ldt) {
                return Timestamp.valueOf(ldt);
            }
        }
        return raw;
    }

    /** 把字符串主键按主键字段类型转换（getOneById 用） */
    private static Object convert(String value, Class<?> type) {
        if (type == int.class || type == Integer.class) {
            return Integer.valueOf(value);
        }
        if (type == long.class || type == Long.class) {
            return Long.valueOf(value);
        }
        return value;
    }

    /** 把数据库生成的主键值转换成主键字段的类型（save 回填用） */
    private static Object convertToId(Object key, Class<?> type) {
        if (key == null) {
            return null;
        }
        if (type == int.class || type == Integer.class) {
            return ((Number) key).intValue();
        }
        if (type == long.class || type == Long.class) {
            return ((Number) key).longValue();
        }
        return key;
    }
}
